export type Cond =
  | { kind: 'type'; types: string[] }
  | { kind: 'flow'; source?: string[]; target?: string[]; origin?: ContentOrigin[]; crosses?: boolean; crossKinds?: BoundaryKind[]; plane?: Plane; encrypted?: string[] }
  | { kind: 'has'; types: string[] }
  | { kind: 'lacks'; types: string[] }
  | { kind: 'connected'; types: string[]; direction: 'in' | 'out' | 'any' }
  | { kind: 'intake'; field: keyof Intake; in: string[] }
  | { kind: 'answer'; q: string; in: AnswerStatus[] }
  | { kind: 'data'; min: DataClass } // component holds / flow carries at least this sensitivity
  | { kind: 'dataAboveApproval' } // component receives data above its own classification
  | { kind: 'any'; conds: Cond[] }
  | { kind: 'all'; conds: Cond[] }
  | { kind: 'not'; cond: Cond };

export interface Signal {
  q: string;
  in: AnswerStatus[];
  note: string;
  /** Added to suggested likelihood (default 1). */
  bump?: number;
}

export interface ThreatRule {
  id: string;
  domain: string;
  scope: 'component' | 'flow' | 'system';
  when: Cond[];
  /** For system scope: components of these types are linked to the threat. */
  involves?: string[];
  title: string;
  actor: string;
  asset: string;
  objectives: ObjectiveId[];
  preconditions: string;
  attackPath: string;
  impact: string;
  tags: FrameworkRef[];
  patterns: string[];
  likelihood: Level;
  impactLevel: Level;
  /** Likelihood +1 when the system is publicly exposed. */
  external?: boolean;
  signals?: Signal[];
}

/** 'owasp-llm:LLM01' → { fw, id } */
const t = (...refs: string[]): FrameworkRef[] =>
  refs.map((r) => {
    const i = r.indexOf(':');
    return { fw: r.slice(0, i), id: r.slice(i + 1) };
  });

